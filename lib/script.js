/**
 * The detached restart script.
 *
 * Runs as `powershell.exe` after the DSH window is already gone, so it must be
 * linear, idempotent enough to survive a half-failure, and self-logging: the log
 * line is the only evidence left when a restart does not come back.
 * @module dsh-quick-restart/script
 */
import { tmpdir } from 'node:os';
import { join } from 'node:path';

export const SCRIPT_NAME = 'dsh-quick-restart.ps1';
export const LOG_NAME = 'dsh-quick-restart.log';

/** Quote one value for a PowerShell single-quoted string. */
export function quotePowerShell(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** Absolute path of the script this plugin writes and runs. */
export function scriptPath() {
  return join(tmpdir(), SCRIPT_NAME);
}

/** Absolute path of the log the script appends to. */
export function logPath() {
  return join(tmpdir(), LOG_NAME);
}

/**
 * Render the script.
 *
 * Order matters: the descendant snapshot has to be taken while the tree is
 * still intact, so it happens before the root is killed. Killing is by pid and
 * by that snapshot only — never by process name — so a second DSH installation
 * (or a second copy of this one) survives a restart here.
 * @param target - resolved `{ pid, exe }`.
 */
export function scriptBody(target) {
  const pid = target.pid;
  const exe = quotePowerShell(target.exe);
  const log = quotePowerShell(logPath());
  return `# generated by dsh-quick-restart — safe to delete
$ErrorActionPreference = 'Continue'
$log = ${log}
function Note([string]$text) {
  "$(Get-Date -Format o) $text" | Out-File -LiteralPath $log -Append -Encoding utf8
}
Note "restart requested: pid ${pid} ($(${exe}))"

# Let the HTTP response reach the page before the process that owns it dies.
Start-Sleep -Milliseconds 900

# Snapshot this shell's descendants BEFORE killing the root. Windows keeps the
# dead parent id on orphaned children, but that id could be reused later, so the
# snapshot is what the wait and the fallback work from.
$rootPid = ${pid}
$all = @(Get-CimInstance Win32_Process -ErrorAction SilentlyContinue | Select-Object ProcessId, ParentProcessId)
$tree = @{}
$queue = New-Object System.Collections.Queue
$queue.Enqueue($rootPid)
while ($queue.Count -gt 0) {
  $parent = [int]$queue.Dequeue()
  foreach ($p in $all) {
    $child = [int]$p.ProcessId
    if ([int]$p.ParentProcessId -eq $parent -and -not $tree.ContainsKey($child)) {
      $tree[$child] = $true
      $queue.Enqueue($child)
    }
  }
}
# This script was spawned by the desktop host, so it IS a descendant of the root
# and would otherwise wait for itself and then kill itself. Exclude it.
$children = @($tree.Keys | Where-Object { $_ -ne $PID })
Note "descendants: $($children.Count) (self excluded)"

# 1) Kill the Electron main process only. Its children lose the pipe and exit
#    gracefully — the desktop host flushes the session log on disconnect.
try {
  Stop-Process -Id $rootPid -Force -ErrorAction Stop
  Note "killed main process $rootPid"
} catch {
  Note "kill main failed: $($_.Exception.Message)"
}

# 2) Wait for the snapshot to leave on its own.
$deadline = (Get-Date).AddSeconds(12)
while ((Get-Date) -lt $deadline) {
  $alive = @($children | Where-Object { Get-Process -Id $_ -ErrorAction SilentlyContinue })
  if ($alive.Count -eq 0) { break }
  Start-Sleep -Milliseconds 400
}

# 3) Fallback: only the processes this shell owned — never another installation,
#    never a second copy the user has open.
$left = @($children | Where-Object { Get-Process -Id $_ -ErrorAction SilentlyContinue })
if ($left.Count -gt 0) {
  Note "fallback kill: $($left.Count) leftover process(es)"
  $left | ForEach-Object { Stop-Process -Id $_ -Force -ErrorAction SilentlyContinue }
  Start-Sleep -Milliseconds 900
}

# 4) Relaunch. The DSH host runs as a Node runtime inside Electron's binary, so
#    the environment this script inherited carries ELECTRON_RUN_AS_NODE=1.
#    A fresh window that inherits it starts as a bare Node process and exits at
#    once (seen in the field: window closed, never came back). Drop it first.
Remove-Item Env:ELECTRON_RUN_AS_NODE -ErrorAction SilentlyContinue
Remove-Item Env:ELECTRON_NO_ATTACH_CONSOLE -ErrorAction SilentlyContinue
$exeDir = Split-Path -Parent ${exe}
function Start-Window {
  Start-Process -FilePath ${exe} -WorkingDirectory $exeDir -PassThru -ErrorAction Stop
}
try {
  $window = Start-Window
  Start-Sleep -Seconds 3
  if (-not $window.HasExited) {
    Note "relaunched pid $($window.Id)"
  } else {
    Note "relaunch exited early: code $($window.ExitCode) (retrying once)"
    Start-Sleep -Seconds 2
    $window = Start-Window
    Start-Sleep -Seconds 3
    if (-not $window.HasExited) {
      Note "relaunched pid $($window.Id) on retry"
    } else {
      Note "relaunch retry also exited: code $($window.ExitCode) (falling back to the shell)"
      Start-Process -FilePath 'explorer.exe' -ArgumentList ${exe} | Out-Null
    }
  }
} catch {
  Note "relaunch failed: $($_.Exception.Message)"
}
`;
}
